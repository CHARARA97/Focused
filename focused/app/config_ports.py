from __future__ import annotations

from typing import Any, Dict, List, Protocol


class ConfigPorts(Protocol):
    def set_enforcement_enabled(self, enabled: bool) -> None: ...

    def apply_rules(self, payload: Dict[str, Any], source: str = "config") -> Any: ...

    def sources(self) -> Dict[str, Any]: ...

    def set_url_patterns(self, patterns: Any, source: str = "config") -> List[str]: ...

    def config_dict(self) -> Dict[str, Any]: ...

    def set_http_token(self, token: str) -> None: ...

    def emit(self, kind: str, **fields: Any) -> Dict[str, Any]: ...
